from __future__ import annotations

import re

import widlparser

from .. import config, dfns, h, t
from .. import messages as m
from .markers import IDLUI, DebugIDLBuilder, IDLBuilder, IDLSilent, IDLTreeBuilder
from .merge import mergeMarkup


class IDLParser(widlparser.parser.Parser):
    """`widlparser.Parser` subclass that can defer symbol lookups during single-pass parsing."""

    deferSymbolLookup: bool = False

    def get_type(self, name: str) -> widlparser.Construct | None:
        if self.deferSymbolLookup:
            return None
        return super().get_type(name)


def markupIDL(doc: t.SpecT) -> None:
    idlEls = h.findAll("pre.idl:not([bs-no-idl]), xmp.idl:not([bs-no-idl])", doc)
    for el in h.findAll("script[type=idl]", doc):
        # To help with syntax-highlighting, <script type=idl> is also allowed here.
        idlEls.append(el)
        el.tag = "pre"
        h.removeAttr(el, "type")
        h.addClass(doc, el, "idl")
    if not idlEls:
        return

    assert isinstance(doc.widl, IDLParser)
    # Single parse pass into doc.widl, deferring symbol lookups (which widlparser
    # only uses during parsing to validate required dictionary arguments) until
    # every block's symbols are registered.
    doc.widl.deferSymbolLookup = True
    parsedBlocks: list[tuple[t.ElementT, IDLUI, t.ElementT | None, list[widlparser.Construct]]] = []
    for el in idlEls:
        if h.isNormative(doc, el):
            extraneousXmp = checkForExtraneousXmp(el)
            text = h.textContent(el)
            ui = IDLUI.fromEl(el, buffered=True)
            doc.widl.ui = ui
            startIdx = len(doc.widl.constructs)
            doc.widl.parse(text)
            parsedBlocks.append((el, ui, extraneousXmp, doc.widl.constructs[startIdx:]))
        h.addClass(doc, el, "highlight")
    doc.widl.ui = IDLSilent()
    doc.widl.deferSymbolLookup = False
    doc.extraJC.addIDLHighlighting()

    # Build lxml markup directly from the already-parsed constructs and run the
    # deferred required-dictionary-argument check against the full symbol table.
    symbolTable = doc.widl.symbol_table
    for el, ui, extraneousXmp, blockConstructs in parsedBlocks:
        if extraneousXmp is not None:
            m.warn("Instead of nesting an <xmp> inside of <pre>, just use an <xmp> directly.", el=extraneousXmp)
        ui.flush()
        builder: IDLTreeBuilder = DebugIDLBuilder() if doc.debug else IDLBuilder()
        if len(el) == 0:
            builder.buildIntoConstructs(el, blockConstructs, symbolTable=symbolTable, ui=ui)
            if isinstance(builder, IDLBuilder) and builder.errors:
                for error in builder.errors:
                    m.die(error, el=el)
        else:
            parsed = builder.buildNodesFromConstructs(blockConstructs, symbolTable=symbolTable, ui=ui)
            if isinstance(builder, IDLBuilder) and builder.errors:
                for error in builder.errors:
                    m.die(error, el=el)
            merged = mergeMarkup(el, parsed)
            h.replaceContents(el, merged)


def checkForExtraneousXmp(el: t.ElementT) -> t.ElementT | None:
    # Some specs do <pre class=idl><xmp>...</xmp></pre>,
    # which makes the markup-merger complain.
    # Strip the xmp out; it performed its duties of safely parsing.
    # Return the stripped element so the caller can warn in document order.
    onlyChild = h.hasOnlyChild(el)
    if onlyChild is None:
        return None
    if h.hasAttr(onlyChild, "bs-was-xmp"):
        h.transferAttributes(onlyChild, el, mergeClass=True)
        h.replaceWithContents(onlyChild)
        return onlyChild
    return None


def markupIDLBlock(pre: t.ElementT, doc: t.SpecT) -> set[t.ElementT]:
    localDfns = set()
    forcedInterfaces = []
    for x in (h.treeAttr(pre, "bs-dfn-force") or "").split():
        x = x.strip()
        if x.endswith("<interface>"):
            x = x[:-11]
        forcedInterfaces.append(x)
    for el in h.findAll("idl", pre):
        idlType = el.get("bs-idl-type")
        if idlType is None:
            m.die(
                "PROGRAMMING ERROR: An <idl> element (auto-generated by Bikeshed) ended up without a bs-idl-type attribute. Please report this!",
                el=el,
            )
            continue
        forceDfn = False
        ref = None
        idlText: str
        for idlText in (el.get("bs-lt") or "").split("|"):
            if idlType == "interface" and idlText in forcedInterfaces:
                forceDfn = True
            linkFors = t.cast("list[str|None]", config.splitForValues(el.get("bs-idl-for", ""))) or [None]
            for linkFor in linkFors:
                ref = doc.refs.getRef(
                    text=idlText,
                    linkType=idlType,
                    linkFor=linkFor,
                    status="local",
                    el=el,
                    error=False,
                )
                if ref:
                    break
            if ref:
                break
        if ref is None or isinstance(ref, str) or forceDfn:
            el.tag = "dfn"
            el.set("data-dfn-type", idlType)
            if (idlLt := el.get("bs-lt")) is not None:
                el.set("data-lt", idlLt)
                h.removeAttr(el, "bs-lt")
            if idlFor := el.get("bs-idl-for"):
                el.set("data-dfn-for", idlFor)
        else:
            # Copy over the auto-generated linking text to the manual dfn.
            dfn = ref.el
            # How in the hell does this work, the url is not a selector???
            assert dfn is not None
            lts = combineIdlLinkingTexts(el.get("bs-lt"), dfn.get("data-lt"))
            dfn.set("data-lt", lts)
            localDfns.add(dfn)

            # Reset the <idl> element to be a link to the manual dfn.
            el.tag = "a"
            el.set("data-link-type", idlType)
            el.set("bs-lt", idlText)
            if idlFor := el.get("bs-idl-for"):
                el.set("bs-link-for", idlFor)
            if el.get("id"):
                # ID was defensively added by the Marker.
                del el.attrib["id"]
    return localDfns


def combineIdlLinkingTexts(t1: str | None, t2: str | None) -> str:
    t1s = [normalizeIdlWhitespace(x) for x in (t1 or "").split("|")]
    t2s = [normalizeIdlWhitespace(x) for x in (t2 or "").split("|")]
    for lt in t2s:
        if lt not in t1s:
            t1s.append(lt)
    return "|".join(t1s)


def normalizeIdlWhitespace(text: str) -> str:
    # Remove all whitespace...
    text = re.sub(r"\s+", "", text)
    # Then add whitespace after commas
    text = re.sub(r",", ", ", text)
    return text


def getParser() -> IDLParser:
    return IDLParser(ui=IDLSilent())


def processIDL(doc: t.SpecT) -> None:
    localDfns = set()
    for pre in h.findAll("pre.idl, xmp.idl", doc):
        if pre.get("bs-no-idl") is not None:
            continue
        if not h.isNormative(doc, pre):
            continue
        localDfns.update(markupIDLBlock(pre, doc))

    idlDfns = h.findAll("pre.idl:not([bs-no-idl]) dfn, xmp.idl:not([bs-no-idl]) dfn", doc) + list(localDfns)
    idlDfns = sorted(idlDfns, key=lambda x: (x.get("bs-line-number") or "", h.textContent(x)))
    dfns.classifyDfns(doc, idlDfns)
    h.fixupIDs(doc, idlDfns)
    doc.refs.addLocalDfns(doc, (dfn for dfn in idlDfns if dfn.get("id") is not None))
